export function getArticleBySlug(slug: string): Article | undefined {
  return ARTICLES.find((article) => article.slug === slug);
}

export function getArticlesBySection(section: Article['section']): Article[] {
  return ARTICLES.filter((article) => article.section === section).sort(byDateDesc);
}

export function getRelatedArticles(current: Article, limit = 3): Article[] {
  const sameCategory = ARTICLES.filter(
    (article) => article.slug !== current.slug && article.category === current.category,
  );
  const others = ARTICLES.filter(
    (article) => article.slug !== current.slug && article.category !== current.category,
  );
  return [...sameCategory, ...others].slice(0, limit);
}

export function byDateDesc(a: Article, b: Article): number {
  return b.date.localeCompare(a.date);
}
